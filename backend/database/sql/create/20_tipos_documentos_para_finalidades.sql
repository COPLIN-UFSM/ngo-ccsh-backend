CREATE TABLE ORCAMENTO.TIPOS_DOCUMENTOS_PARA_FINALIDADES (
    ID_TIPO_DOCUMENTO_PARA_FINALIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY
        NOT NULL PRIMARY KEY,
    ID_TIPO_DOCUMENTO INTEGER NOT NULL,
    ID_FINALIDADE INTEGER NOT NULL,
    OBRIGATORIO BOOLEAN NOT NULL DEFAULT TRUE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT UK_TIPO_DOCUMENTO_FINALIDADE
        UNIQUE (ID_TIPO_DOCUMENTO, ID_FINALIDADE),
    CONSTRAINT FK_TDPF_TIPO_DOCUMENTO FOREIGN KEY (ID_TIPO_DOCUMENTO)
        REFERENCES ORCAMENTO.TIPOS_DOCUMENTOS (ID_TIPO_DOCUMENTO),
    CONSTRAINT FK_TDPF_FINALIDADE FOREIGN KEY (ID_FINALIDADE)
        REFERENCES ORCAMENTO.FINALIDADES (ID_FINALIDADE)
);

COMMENT ON TABLE ORCAMENTO.TIPOS_DOCUMENTOS_PARA_FINALIDADES
    IS 'Documentos aceitos ou exigidos por finalidade.';
COMMENT ON COLUMN ORCAMENTO.TIPOS_DOCUMENTOS_PARA_FINALIDADES.OBRIGATORIO
    IS 'Se este tipo de documento é obrigatório para esta finalidade';
COMMENT ON COLUMN ORCAMENTO.TIPOS_DOCUMENTOS_PARA_FINALIDADES.ATIVO
    IS 'Se esta relação está atualmente ativa ou não';