CREATE TABLE ORCAMENTO.DESPESAS_HISTORICALPARCELABOLSA (
    ID_PARCELA_BOLSA INTEGER NOT NULL,
    COMPETENCIA DATE NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    VALOR DECIMAL(15, 2) NOT NULL,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'prevista',
    ID_VINCULO_BOLSA INTEGER,
    ID_EMPENHO_PREVISTO INTEGER,
    HISTORY_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    HISTORY_DATE TIMESTAMP NOT NULL,
    HISTORY_CHANGE_REASON VARCHAR(100),
    HISTORY_TYPE CHAR(1) NOT NULL,
    HISTORY_USER_ID INTEGER,
    CONSTRAINT CK_HIST_PARCELA_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT FK_HIST_PARCELA_USUARIO FOREIGN KEY (HISTORY_USER_ID)
        REFERENCES ORCAMENTO.USUARIOS (ID)
);

COMMENT ON TABLE ORCAMENTO.DESPESAS_HISTORICALPARCELABOLSA IS 'Histórico de alterações de parcelas de bolsa.';
