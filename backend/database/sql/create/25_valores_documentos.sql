CREATE TABLE ORCAMENTO.VALORES_DOCUMENTOS (
    ID_VALOR_DOCUMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_TRANSACAO INTEGER NOT NULL,
    ID_TIPO_DOCUMENTO INTEGER NOT NULL,
    ORDEM SMALLINT NOT NULL DEFAULT 0,
    VALOR VARCHAR(256) NOT NULL,
    CONSTRAINT CK_VALOR_DOC_ORDEM_NAO_NEGATIVA CHECK (ORDEM >= 0),
    CONSTRAINT UK_VALOR_DOCUMENTO_ORDEM
        UNIQUE (ID_TRANSACAO, ID_TIPO_DOCUMENTO, ORDEM),
    CONSTRAINT FK_VALOR_DOC_TRANSACAO FOREIGN KEY (ID_TRANSACAO)
        REFERENCES ORCAMENTO.TRANSACOES (ID_TRANSACAO),
    CONSTRAINT FK_VALOR_DOC_TIPO FOREIGN KEY (ID_TIPO_DOCUMENTO)
        REFERENCES ORCAMENTO.TIPOS_DOCUMENTOS (ID_TIPO_DOCUMENTO)
);

COMMENT ON TABLE ORCAMENTO.VALORES_DOCUMENTOS IS 'Valores de documentos associados a transações.';