CREATE TABLE ORCAMENTO.PARCELAS_BOLSAS (
    ID_PARCELA_BOLSA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_VINCULO_BOLSA INTEGER NOT NULL,
    COMPETENCIA DATE NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    VALOR DECIMAL(15, 2) NOT NULL,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'prevista',
    ID_EMPENHO_PREVISTO INTEGER,
    CONSTRAINT CK_PARCELA_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT UK_PARCELA_VINCULO_COMPETENCIA UNIQUE (ID_VINCULO_BOLSA, COMPETENCIA),
    CONSTRAINT FK_PARCELA_VINCULO FOREIGN KEY (ID_VINCULO_BOLSA)
        REFERENCES ORCAMENTO.VINCULOS_BOLSAS (ID_VINCULO_BOLSA),
    CONSTRAINT FK_PARCELA_EMPENHO FOREIGN KEY (ID_EMPENHO_PREVISTO)
        REFERENCES ORCAMENTO.EMPENHOS (ID_EMPENHO)
);

CREATE INDEX ORCAMENTO.IX_PARCELAS_STATUS_ANO
    ON ORCAMENTO.PARCELAS_BOLSAS (STATUS, ANO_FISCAL);

COMMENT ON TABLE ORCAMENTO.PARCELAS_BOLSAS IS 'Parcelas mensais dos vínculos de bolsa.';
