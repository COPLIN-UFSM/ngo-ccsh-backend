CREATE TABLE ORCAMENTO.CENTROS (
    ID_CENTRO_INTERNO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_CENTRO_SIE INTEGER,
    NOME_CENTRO VARCHAR(256) NOT NULL,
    SIGLA_CENTRO VARCHAR(16) NOT NULL UNIQUE,
    COD_ESTRUTURADO VARCHAR(15) NOT NULL UNIQUE
);

COMMENT ON TABLE ORCAMENTO.CENTROS IS 'Centros internos do sistema financeiro.';