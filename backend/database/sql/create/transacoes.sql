CREATE TABLE ORCAMENTO.TRANSACOES (
    ID_TRANSACAO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    OPERACAO VARCHAR(32) NOT NULL,
    DATA DATE NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    CRIADA_EM TIMESTAMP NOT NULL,
    JUSTIFICATIVA CLOB(1M) NOT NULL,
    ID_TRANSACAO_CORRIGIDA INTEGER,
    ESTIMADA BOOLEAN NOT NULL DEFAULT FALSE,
    ID_BENEFICIARIO INTEGER,
    CONSTRAINT FK_TRANSACAO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES ORCAMENTO.USUARIOS (ID),
    CONSTRAINT FK_TRANSACAO_CORRIGIDA FOREIGN KEY (ID_TRANSACAO_CORRIGIDA)
        REFERENCES ORCAMENTO.TRANSACOES (ID_TRANSACAO),
    CONSTRAINT FK_TRANSACAO_BENEFICIARIO FOREIGN KEY (ID_BENEFICIARIO)
        REFERENCES ORCAMENTO.PESSOAS (ID_PESSOA_INTERNA)
);

CREATE INDEX ORCAMENTO.IX_TRANSACOES_DATA ON ORCAMENTO.TRANSACOES (DATA);

COMMENT ON TABLE ORCAMENTO.TRANSACOES IS 'Cabeçalhos imutáveis das operações do razão.';
