CREATE TABLE ORCAMENTO.UNIDADES (
    ID_UNIDADE_INTERNA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_UNIDADE_SIE INTEGER,
    NOME_UNIDADE VARCHAR(256) NOT NULL,
    COD_ESTRUTURADO VARCHAR(15) NOT NULL UNIQUE,
    ID_CENTRO_INTERNO INTEGER NOT NULL,
    ID_UNIDADE_PAI INTEGER,
    ID_TIPO_UNIDADE INTEGER NOT NULL,
    ID_SITUACAO_UNIDADE INTEGER NOT NULL,
    CONSTRAINT CK_UNIDADE_NAO_E_PAI_DE_SI_MESMA
        CHECK (ID_UNIDADE_PAI IS NULL OR ID_UNIDADE_PAI <> ID_UNIDADE_INTERNA),
    CONSTRAINT FK_UNIDADE_CENTRO FOREIGN KEY (ID_CENTRO_INTERNO)
        REFERENCES ORCAMENTO.CENTROS (ID_CENTRO_INTERNO),
    CONSTRAINT FK_UNIDADE_PAI FOREIGN KEY (ID_UNIDADE_PAI)
        REFERENCES ORCAMENTO.UNIDADES (ID_UNIDADE_INTERNA)
);

COMMENT ON TABLE ORCAMENTO.UNIDADES IS 'Unidades internas e hierarquia de unidades.';