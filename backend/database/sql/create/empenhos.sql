CREATE TABLE ORCAMENTO.EMPENHOS (
    ID_EMPENHO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    NUMERO_EMPENHO VARCHAR(32) NOT NULL,
    NUMERO_PEN VARCHAR(32) UNIQUE,
    ID_CENTRO_INTERNO INTEGER NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    ID_NATUREZA INTEGER NOT NULL,
    ID_FINALIDADE INTEGER NOT NULL,
    ID_EMPENHO_ORIGEM INTEGER,
    CRIADO_EM TIMESTAMP NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_EMPENHO_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT UK_EMPENHO_ANO_NUMERO UNIQUE (ANO_FISCAL, NUMERO_EMPENHO),
    CONSTRAINT FK_EMPENHO_CENTRO FOREIGN KEY (ID_CENTRO_INTERNO)
        REFERENCES ORCAMENTO.CENTROS (ID_CENTRO_INTERNO),
    CONSTRAINT FK_EMPENHO_NATUREZA FOREIGN KEY (ID_NATUREZA)
        REFERENCES ORCAMENTO.NATUREZAS (ID_NATUREZA),
    CONSTRAINT FK_EMPENHO_FINALIDADE FOREIGN KEY (ID_FINALIDADE)
        REFERENCES ORCAMENTO.FINALIDADES (ID_FINALIDADE),
    CONSTRAINT FK_EMPENHO_ORIGEM FOREIGN KEY (ID_EMPENHO_ORIGEM)
        REFERENCES ORCAMENTO.EMPENHOS (ID_EMPENHO)
);

COMMENT ON TABLE ORCAMENTO.EMPENHOS IS 'Empenhos vinculados a centro, natureza e finalidade.';