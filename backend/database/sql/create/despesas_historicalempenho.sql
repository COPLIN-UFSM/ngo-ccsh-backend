CREATE TABLE ORCAMENTO.DESPESAS_HISTORICALEMPENHO (
    ID_EMPENHO INTEGER NOT NULL,
    NUMERO_EMPENHO VARCHAR(32) NOT NULL,
    NUMERO_PEN VARCHAR(32),
    ANO_FISCAL SMALLINT NOT NULL,
    CRIADO_EM TIMESTAMP NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    ID_CENTRO_INTERNO INTEGER,
    ID_NATUREZA INTEGER,
    ID_FINALIDADE INTEGER,
    ID_EMPENHO_ORIGEM INTEGER,
    HISTORY_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    HISTORY_DATE TIMESTAMP NOT NULL,
    HISTORY_CHANGE_REASON VARCHAR(100),
    HISTORY_TYPE CHAR(1) NOT NULL,
    HISTORY_USER_ID INTEGER,
    CONSTRAINT CK_HIST_EMPENHO_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT FK_HIST_EMPENHO_USUARIO FOREIGN KEY (HISTORY_USER_ID)
        REFERENCES ORCAMENTO.USUARIOS (ID)
);

COMMENT ON TABLE ORCAMENTO.DESPESAS_HISTORICALEMPENHO IS 'Histórico de alterações de empenhos.';
