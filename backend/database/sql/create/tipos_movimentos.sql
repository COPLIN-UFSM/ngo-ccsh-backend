CREATE TABLE ORCAMENTO.TIPOS_MOVIMENTOS (
    ID_TIPO_MOVIMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    CODIGO VARCHAR(48) NOT NULL UNIQUE,
    NOME VARCHAR(128) NOT NULL,
    ALTERA_TOTAL BOOLEAN NOT NULL,
    CONTA_COMO_GASTO BOOLEAN NOT NULL DEFAULT FALSE
);

COMMENT ON TABLE ORCAMENTO.TIPOS_MOVIMENTOS IS 'Tipos de movimento do razão.';
