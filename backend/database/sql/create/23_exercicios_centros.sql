CREATE TABLE ORCAMENTO.EXERCICIOS_CENTROS (
    ID_EXERCICIO_CENTRO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_CENTRO_INTERNO INTEGER NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'aberto',
    ID_TRANSACAO_FECHAMENTO INTEGER,
    CONSTRAINT CK_EXERCICIO_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT UK_EXERCICIO_CENTRO_ANO UNIQUE (ID_CENTRO_INTERNO, ANO_FISCAL),
    CONSTRAINT FK_EXERCICIO_CENTRO FOREIGN KEY (ID_CENTRO_INTERNO)
        REFERENCES ORCAMENTO.CENTROS (ID_CENTRO_INTERNO),
    CONSTRAINT FK_EXERCICIO_TRANSACAO FOREIGN KEY (ID_TRANSACAO_FECHAMENTO)
        REFERENCES ORCAMENTO.TRANSACOES (ID_TRANSACAO)
);

COMMENT ON TABLE ORCAMENTO.EXERCICIOS_CENTROS IS 'Estado anual do exercício por centro.';
