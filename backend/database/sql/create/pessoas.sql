CREATE TABLE ORCAMENTO.PESSOAS (
    ID_PESSOA_INTERNA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_PESSOA_SIE INTEGER,
    NOME_PESSOA VARCHAR(256) NOT NULL,
    CPF VARCHAR(11) NOT NULL UNIQUE,
    RG VARCHAR(11) NOT NULL UNIQUE
);

COMMENT ON TABLE ORCAMENTO.PESSOAS IS 'Pessoas internas e beneficiários externos.';