CREATE TABLE ORCAMENTO.VINCULOS_BOLSAS (
    ID_VINCULO_BOLSA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_PESSOA_INTERNA INTEGER NOT NULL,
    ID_UNIDADE_INTERNA INTEGER NOT NULL,
    ID_FINALIDADE INTEGER NOT NULL,
    VALOR_MENSAL DECIMAL(15, 2) NOT NULL,
    INICIO DATE NOT NULL,
    FIM DATE NOT NULL,
    CONSTRAINT CK_VINCULO_FIM_APOS_INICIO CHECK (FIM >= INICIO),
    CONSTRAINT CK_VINCULO_VALOR_POSITIVO CHECK (VALOR_MENSAL > 0),
    CONSTRAINT FK_VINCULO_BOLSISTA FOREIGN KEY (ID_PESSOA_INTERNA)
        REFERENCES ORCAMENTO.PESSOAS (ID_PESSOA_INTERNA),
    CONSTRAINT FK_VINCULO_UNIDADE FOREIGN KEY (ID_UNIDADE_INTERNA)
        REFERENCES ORCAMENTO.UNIDADES (ID_UNIDADE_INTERNA),
    CONSTRAINT FK_VINCULO_FINALIDADE FOREIGN KEY (ID_FINALIDADE)
        REFERENCES ORCAMENTO.FINALIDADES (ID_FINALIDADE)
);

COMMENT ON TABLE ORCAMENTO.VINCULOS_BOLSAS IS 'Vínculos de bolsistas com unidades e finalidades.';
