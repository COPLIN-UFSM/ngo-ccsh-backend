CREATE TABLE ORCAMENTO.DESPESAS_HISTORICALVINCULOBOLSA (
    ID_VINCULO_BOLSA INTEGER NOT NULL,
    VALOR_MENSAL DECIMAL(15, 2) NOT NULL,
    INICIO DATE NOT NULL,
    FIM DATE NOT NULL,
    ID_PESSOA_INTERNA INTEGER,
    ID_UNIDADE_INTERNA INTEGER,
    ID_FINALIDADE INTEGER,
    HISTORY_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    HISTORY_DATE TIMESTAMP NOT NULL,
    HISTORY_CHANGE_REASON VARCHAR(100),
    HISTORY_TYPE CHAR(1) NOT NULL,
    HISTORY_USER_ID INTEGER,
    CONSTRAINT FK_HIST_VINCULO_USUARIO FOREIGN KEY (HISTORY_USER_ID)
        REFERENCES ORCAMENTO.USUARIOS (ID)
);

COMMENT ON TABLE ORCAMENTO.DESPESAS_HISTORICALVINCULOBOLSA IS 'Histórico de alterações de vínculos de bolsa.';
