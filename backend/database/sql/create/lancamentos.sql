CREATE TABLE ORCAMENTO.LANCAMENTOS (
    ID_LANCAMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_TRANSACAO INTEGER NOT NULL,
    ID_TIPO_MOVIMENTO INTEGER NOT NULL,
    ID_CENTRO_INTERNO INTEGER NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    ID_NATUREZA INTEGER NOT NULL,
    ID_EMPENHO INTEGER,
    ID_UNIDADE_INTERNA INTEGER,
    ID_FINALIDADE INTEGER,
    MONTANTE DECIMAL(15, 2) NOT NULL,
    ID_LANCAMENTO_ESTORNADO INTEGER UNIQUE,
    CONSTRAINT CK_LANCAMENTO_MONTANTE_NAO_ZERO CHECK (MONTANTE <> 0),
    CONSTRAINT CK_LANCAMENTO_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT FK_LANCAMENTO_TRANSACAO FOREIGN KEY (ID_TRANSACAO)
        REFERENCES ORCAMENTO.TRANSACOES (ID_TRANSACAO),
    CONSTRAINT FK_LANCAMENTO_TIPO FOREIGN KEY (ID_TIPO_MOVIMENTO)
        REFERENCES ORCAMENTO.TIPOS_MOVIMENTOS (ID_TIPO_MOVIMENTO),
    CONSTRAINT FK_LANCAMENTO_CENTRO FOREIGN KEY (ID_CENTRO_INTERNO)
        REFERENCES ORCAMENTO.CENTROS (ID_CENTRO_INTERNO),
    CONSTRAINT FK_LANCAMENTO_NATUREZA FOREIGN KEY (ID_NATUREZA)
        REFERENCES ORCAMENTO.NATUREZAS (ID_NATUREZA),
    CONSTRAINT FK_LANCAMENTO_EMPENHO FOREIGN KEY (ID_EMPENHO)
        REFERENCES ORCAMENTO.EMPENHOS (ID_EMPENHO),
    CONSTRAINT FK_LANCAMENTO_UNIDADE FOREIGN KEY (ID_UNIDADE_INTERNA)
        REFERENCES ORCAMENTO.UNIDADES (ID_UNIDADE_INTERNA),
    CONSTRAINT FK_LANCAMENTO_FINALIDADE FOREIGN KEY (ID_FINALIDADE)
        REFERENCES ORCAMENTO.FINALIDADES (ID_FINALIDADE),
    CONSTRAINT FK_LANCAMENTO_ESTORNO FOREIGN KEY (ID_LANCAMENTO_ESTORNADO)
        REFERENCES ORCAMENTO.LANCAMENTOS (ID_LANCAMENTO)
);

CREATE INDEX ORCAMENTO.IX_LANCAMENTOS_EMPENHO
    ON ORCAMENTO.LANCAMENTOS (ID_EMPENHO);
CREATE INDEX ORCAMENTO.IX_LANCAMENTOS_UNIDADE_ANO_NATUREZA
    ON ORCAMENTO.LANCAMENTOS (ID_UNIDADE_INTERNA, ANO_FISCAL, ID_NATUREZA);
CREATE INDEX ORCAMENTO.IX_LANCAMENTOS_CENTRO_ANO_NATUREZA
    ON ORCAMENTO.LANCAMENTOS (ID_CENTRO_INTERNO, ANO_FISCAL, ID_NATUREZA);

COMMENT ON TABLE ORCAMENTO.LANCAMENTOS IS 'Razão imutável de entradas, reservas e despesas.';
