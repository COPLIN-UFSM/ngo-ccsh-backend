CREATE TABLE ORCAMENTO.ITENS_LISTAS_SIAFI (
    ID_ITEM_LISTA_SIAFI INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_LISTA_SIAFI INTEGER NOT NULL,
    ID_PARCELA_BOLSA INTEGER NOT NULL UNIQUE,
    VALOR DECIMAL(15, 2) NOT NULL,
    CONSTRAINT FK_ITEM_LISTA FOREIGN KEY (ID_LISTA_SIAFI)
        REFERENCES ORCAMENTO.LISTAS_SIAFI (ID_LISTA_SIAFI),
    CONSTRAINT FK_ITEM_PARCELA FOREIGN KEY (ID_PARCELA_BOLSA)
        REFERENCES ORCAMENTO.PARCELAS_BOLSAS (ID_PARCELA_BOLSA)
);

COMMENT ON TABLE ORCAMENTO.ITENS_LISTAS_SIAFI IS 'Parcelas incluídas em listas SIAFI.';
