CREATE TABLE ORCAMENTO.TELEFONES (
    ID_TELEFONE INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_PESSOA_INTERNA INTEGER NOT NULL,
    TELEFONE VARCHAR(16) NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_TELEFONE_PESSOA FOREIGN KEY (ID_PESSOA_INTERNA)
        REFERENCES ORCAMENTO.PESSOAS (ID_PESSOA_INTERNA)
);

COMMENT ON TABLE ORCAMENTO.TELEFONES IS 'Telefones de pessoas.';