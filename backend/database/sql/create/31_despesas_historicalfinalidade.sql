CREATE TABLE ORCAMENTO.DESPESAS_HISTORICALFINALIDADE (
    ID_FINALIDADE INTEGER NOT NULL,
    NOME VARCHAR(512) NOT NULL,
    PERMITE_TRANSPORTE BOOLEAN NOT NULL DEFAULT FALSE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    ID_NATUREZA INTEGER,
    ID_GRUPO_FINALIDADE INTEGER,
    HISTORY_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    HISTORY_DATE TIMESTAMP NOT NULL,
    HISTORY_CHANGE_REASON VARCHAR(100),
    HISTORY_TYPE CHAR(1) NOT NULL,
    HISTORY_USER_ID INTEGER,
    CONSTRAINT FK_HIST_FINALIDADE_USUARIO FOREIGN KEY (HISTORY_USER_ID)
        REFERENCES ORCAMENTO.USUARIOS (ID)
);

COMMENT ON TABLE ORCAMENTO.DESPESAS_HISTORICALFINALIDADE IS 'Histórico de alterações de finalidades.';
