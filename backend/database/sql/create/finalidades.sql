CREATE TABLE ORCAMENTO.FINALIDADES (
    ID_FINALIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    NOME VARCHAR(512) NOT NULL UNIQUE,
    ID_NATUREZA INTEGER NOT NULL,
    ID_GRUPO_FINALIDADE INTEGER,
    PERMITE_TRANSPORTE BOOLEAN NOT NULL DEFAULT FALSE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_FINALIDADE_NATUREZA FOREIGN KEY (ID_NATUREZA)
        REFERENCES ORCAMENTO.NATUREZAS (ID_NATUREZA),
    CONSTRAINT FK_FINALIDADE_GRUPO FOREIGN KEY (ID_GRUPO_FINALIDADE)
        REFERENCES ORCAMENTO.GRUPOS_FINALIDADES (ID_GRUPO_FINALIDADE)
);

COMMENT ON TABLE ORCAMENTO.FINALIDADES IS 'Destinos orçamentários classificados por natureza.';