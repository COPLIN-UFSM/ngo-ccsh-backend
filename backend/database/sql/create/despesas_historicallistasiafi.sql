CREATE TABLE ORCAMENTO.DESPESAS_HISTORICALLISTASIAFI (
    ID_LISTA_SIAFI INTEGER NOT NULL,
    COMPETENCIA DATE NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    NUMERO_SIAFI VARCHAR(64),
    STATUS VARCHAR(16) NOT NULL DEFAULT 'rascunho',
    CRIADA_EM TIMESTAMP NOT NULL,
    ID_CENTRO_INTERNO INTEGER,
    ID_TRANSACAO INTEGER,
    HISTORY_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    HISTORY_DATE TIMESTAMP NOT NULL,
    HISTORY_CHANGE_REASON VARCHAR(100),
    HISTORY_TYPE CHAR(1) NOT NULL,
    HISTORY_USER_ID INTEGER,
    CONSTRAINT CK_HIST_LISTA_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT FK_HIST_LISTA_USUARIO FOREIGN KEY (HISTORY_USER_ID)
        REFERENCES ORCAMENTO.USUARIOS (ID)
);

COMMENT ON TABLE ORCAMENTO.DESPESAS_HISTORICALLISTASIAFI IS 'Histórico de alterações de listas SIAFI.';
