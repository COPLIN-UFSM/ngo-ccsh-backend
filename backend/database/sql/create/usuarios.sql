CREATE TABLE ORCAMENTO.USUARIOS (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    CPF VARCHAR(11) NOT NULL UNIQUE,
    EMAIL VARCHAR(64) NOT NULL UNIQUE,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    IS_SUPERUSER BOOLEAN NOT NULL DEFAULT FALSE,
    PASSWORD VARCHAR(128) NOT NULL,
    LAST_LOGIN TIMESTAMP,
    CREATED_AT TIMESTAMP NOT NULL,
    ID_PESSOA INTEGER NOT NULL UNIQUE,
    CONSTRAINT FK_USUARIO_PESSOA FOREIGN KEY (ID_PESSOA)
        REFERENCES ORCAMENTO.PESSOAS (ID_PESSOA_INTERNA)
);

COMMENT ON TABLE ORCAMENTO.USUARIOS IS 'Usuários da aplicação financeira.';