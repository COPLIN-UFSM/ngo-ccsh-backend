CREATE TABLE ORCAMENTO.LISTAS_SIAFI (
    ID_LISTA_SIAFI INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_CENTRO_INTERNO INTEGER NOT NULL,
    COMPETENCIA DATE NOT NULL,
    ANO_FISCAL SMALLINT NOT NULL,
    NUMERO_SIAFI VARCHAR(64) UNIQUE,
    STATUS VARCHAR(16) NOT NULL DEFAULT 'rascunho',
    ID_TRANSACAO INTEGER UNIQUE,
    CRIADA_EM TIMESTAMP NOT NULL,
    CONSTRAINT CK_LISTA_ANO_NAO_NEGATIVO CHECK (ANO_FISCAL >= 0),
    CONSTRAINT FK_LISTA_CENTRO FOREIGN KEY (ID_CENTRO_INTERNO)
        REFERENCES ORCAMENTO.CENTROS (ID_CENTRO_INTERNO),
    CONSTRAINT FK_LISTA_TRANSACAO FOREIGN KEY (ID_TRANSACAO)
        REFERENCES ORCAMENTO.TRANSACOES (ID_TRANSACAO)
);

COMMENT ON TABLE ORCAMENTO.LISTAS_SIAFI IS 'Listas mensais de pagamento SIAFI.';
