CREATE TABLE ORCAMENTO.TIPOS_DOCUMENTOS (
    ID_TIPO_DOCUMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    NOME VARCHAR(128) NOT NULL UNIQUE,
    TIPO_DADO VARCHAR(16) NOT NULL DEFAULT 'texto',
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT CK_TIPO_DOCUMENTO_DADO
        CHECK (TIPO_DADO IN ('texto', 'data', 'numero'))
);

COMMENT ON TABLE ORCAMENTO.TIPOS_DOCUMENTOS IS 'Campos e documentos exigidos para despesas.';