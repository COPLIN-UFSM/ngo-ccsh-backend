CREATE TABLE ORCAMENTO.EMAILS (
    ID_EMAIL INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    ID_PESSOA_INTERNA INTEGER NOT NULL,
    EMAIL VARCHAR(254) NOT NULL UNIQUE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_EMAIL_PESSOA FOREIGN KEY (ID_PESSOA_INTERNA)
        REFERENCES ORCAMENTO.PESSOAS (ID_PESSOA_INTERNA)
);

COMMENT ON TABLE ORCAMENTO.EMAILS IS 'Endereços de email das pessoas.';