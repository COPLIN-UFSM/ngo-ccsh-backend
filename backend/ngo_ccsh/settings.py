def get_database_parameter(key):
    """
    Tenta ler parâmetros nessa ordem:
    1. Parâmetros pela linha de comando
    2. Arquivo JSON em SECRETS_FILE
    :param key: nome do parâmetro a ser recuperado, seja por linha de comando ou do arquivo database_credentials.json
    """

    # se estiver usando o arquivo de settings test ou dev, que usam banco de dados local sqlite, não precisa coletar
    # os parâmetros nem da linha de comando, nem do arquivo de configuração
    if "test" in SETTINGS_MODULE.lower() or "dev" in SETTINGS_MODULE.lower():
        return None

    # parâmetro pela CLI
    value = os.getenv(key)
    if value is not None:
        return value

    # arquivo JSON
    if key in DB_PARAMETERS:
        return DB_PARAMETERS[key]

    raise ImproperlyConfigured(f"Não foi encontrado o atributo '{key}' no CLI nem no arquivo {SECRETS_FILE}")


